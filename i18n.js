  function applyLanguage(lang = currentLanguage()) {
    if (!languages[lang]) lang = "en";
    localStorage.setItem("pcw_language", lang);
    document.documentElement.lang = languages[lang].htmlLang;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      element.textContent = copy[lang][element.dataset.i18n] || copy.en[element.dataset.i18n] || element.textContent;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      element.setAttribute("placeholder", copy[lang][element.dataset.i18nPlaceholder] || copy.en[element.dataset.i18nPlaceholder] || "");
    });
    document.querySelectorAll(".language-select").forEach((select) => {
      select.value = lang;
    });
    window.dispatchEvent(new CustomEvent("pcw:languagechange", { detail: { lang } }));
  }

  function init() {
    document.querySelectorAll(".language-select").forEach((select) => {
      select.innerHTML = Object.entries(languages).map(([code, language]) => `<option value="${code}">${language.label}</option>`).join("");
      select.addEventListener("change", () => applyLanguage(select.value));
    });
    applyLanguage();
  }

  document.addEventListener("DOMContentLoaded", init);

